#!/usr/bin/env python3
"""Generate QuickBite's ORIGINAL placeholder food artwork (Milestone 5).

The assignment forbids unlicensed assets, and the seeded API deliberately has
no image URLs — so the Flutter app uses intentional, attractive placeholders
generated by THIS script: stylized top-down dishes (abstract ingredient
composition on a white plate over a warm gradient) plus a restaurant hero
banner and the app logo mark. Everything here is original geometry drawn with
PIL; no third-party photography or traced artwork is used.

Deterministic output (seeded RNG per variant): re-running produces identical
files. Run from the repository root:

    python3 scripts/generate_food_images.py
"""

from __future__ import annotations

import math
import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

OUT_DIR = Path(__file__).resolve().parents[1] / "frontend" / "assets" / "images"
TILE = 512
SS = 3  # supersampling factor for smooth edges

# Warm backgrounds echoing the design reference (cream/coral family).
BACKGROUNDS = [
    ((255, 244, 236), (253, 224, 205)),  # cream -> peach
    ((255, 248, 240), (255, 226, 214)),  # warm white -> blush
    ((252, 246, 233), (246, 228, 196)),  # cream -> wheat
    ((243, 247, 236), (222, 236, 208)),  # mint cream -> sage
]

PLATE = (255, 253, 250)
PLATE_RIM = (240, 232, 224)


def _lerp(a: tuple, b: tuple, t: float) -> tuple:
    return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))


def _vertical_gradient(size: int, top: tuple, bottom: tuple) -> Image.Image:
    img = Image.new("RGB", (size, size))
    px = img.load()
    for y in range(size):
        row = _lerp(top, bottom, y / (size - 1))
        for x in range(size):
            px[x, y] = row
    return img


def _blob(draw: ImageDraw.ImageDraw, cx: float, cy: float, r: float, color: tuple, rng, jitter=0.25):
    """Irregular rounded ingredient blob."""
    pts = []
    steps = 12
    for i in range(steps):
        ang = 2 * math.pi * i / steps
        rr = r * (1 - jitter / 2 + rng.random() * jitter)
        pts.append((cx + rr * math.cos(ang), cy + rr * math.sin(ang)))
    draw.polygon(pts, fill=color)


def _leaf(draw: ImageDraw.ImageDraw, cx: float, cy: float, r: float, color: tuple, ang: float):
    """Simple two-arc leaf."""
    pts = []
    for i in range(17):
        t = i / 16
        x = (t - 0.5) * 2 * r
        y = math.sin(t * math.pi) * r * 0.55
        pts.append((x, y))
    for i in range(17):
        t = 1 - i / 16
        x = (t - 0.5) * 2 * r
        y = -math.sin(t * math.pi) * r * 0.55
        pts.append((x, y))
    cos_a, sin_a = math.cos(ang), math.sin(ang)
    rotated = [(cx + x * cos_a - y * sin_a, cy + x * sin_a + y * cos_a) for x, y in pts]
    draw.polygon(rotated, fill=color)


def _dish_biryani(d: ImageDraw.ImageDraw, c: float, rng):
    palette = [(232, 172, 62), (245, 208, 120), (250, 236, 200), (205, 110, 48), (120, 168, 84), (176, 74, 58)]
    for _ in range(150):
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.55 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        col = rng.choice(palette[:4])
        if rng.random() < 0.12:
            col = rng.choice(palette[4:])
        d.ellipse([x - c * 0.05, y - c * 0.02, x + c * 0.05, y + c * 0.02], fill=col)
    for _ in range(14):  # herbs + tomato
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.5 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        if rng.random() < 0.5:
            _leaf(d, x, y, c * 0.09, (86, 140, 62), rng.uniform(0, math.pi))
        else:
            _blob(d, x, y, c * 0.06, (198, 62, 48), rng)


def _dish_pizza(d: ImageDraw.ImageDraw, c: float, rng):
    d.ellipse([c * 0.34, c * 0.34, c * 1.66, c * 1.66], fill=(226, 178, 92))       # crust
    d.ellipse([c * 0.45, c * 0.45, c * 1.55, c * 1.55], fill=(206, 74, 48))        # sauce
    for _ in range(9):                                                             # mozzarella
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.62 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _blob(d, x, y, c * 0.13, (250, 238, 214), rng, jitter=0.4)
    for _ in range(7):                                                             # pepperoni
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.58 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        d.ellipse([x - c * 0.09, y - c * 0.09, x + c * 0.09, y + c * 0.09], fill=(166, 44, 38))
    for _ in range(8):                                                             # basil
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.6 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _leaf(d, x, y, c * 0.08, (76, 128, 58), rng.uniform(0, math.pi))


def _dish_salad(d: ImageDraw.ImageDraw, c: float, rng):
    for _ in range(46):
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.52 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        shade = rng.choice([(96, 156, 74), (122, 176, 92), (74, 132, 60), (150, 192, 108)])
        _leaf(d, x, y, c * rng.uniform(0.09, 0.14), shade, rng.uniform(0, math.pi))
    for _ in range(9):  # tomatoes
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.46 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        d.ellipse([x - c * 0.07, y - c * 0.07, x + c * 0.07, y + c * 0.07], fill=(204, 58, 46))
    for _ in range(16):  # corn
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.5 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        d.ellipse([x - c * 0.028, y - c * 0.02, x + c * 0.028, y + c * 0.02], fill=(240, 200, 74))


def _dish_burger(d: ImageDraw.ImageDraw, c: float, rng):
    d.ellipse([c * 0.36, c * 0.36, c * 1.64, c * 1.64], fill=(214, 160, 92))       # bun
    for _ in range(16):                                                             # sesame
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.62 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        d.ellipse([x - c * 0.028, y - c * 0.016, x + c * 0.028, y + c * 0.016], fill=(252, 240, 214))
    d.ellipse([c * 0.28, c * 0.28, c * 1.72, c * 1.72], outline=(190, 138, 74), width=int(c * 0.05))
    # lettuce ruffle ring
    for i in range(18):
        ang = 2 * math.pi * i / 18
        x, y = c + c * 0.66 * math.cos(ang), c + c * 0.66 * math.sin(ang)
        _blob(d, x, y, c * 0.11, (110, 168, 78), rng, jitter=0.5)
    d.ellipse([c * 0.44, c * 0.44, c * 1.56, c * 1.56], fill=(146, 96, 56))         # patty
    d.ellipse([c * 0.52, c * 0.52, c * 1.48, c * 1.48], fill=(176, 74, 54))        # tomato slice
    d.ellipse([c * 0.62, c * 0.62, c * 1.38, c * 1.38], fill=(246, 214, 120))      # cheese


def _dish_pasta(d: ImageDraw.ImageDraw, c: float, rng):
    for i in range(26):                                                              # noodle loops
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.42 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        rr = c * rng.uniform(0.09, 0.16)
        col = rng.choice([(244, 222, 158), (238, 208, 132), (250, 234, 180)])
        d.arc([x - rr, y - rr, x + rr, y + rr], rng.uniform(0, 360), rng.uniform(0, 360), fill=col, width=int(c * 0.055))
    for _ in range(10):                                                              # sauce
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.5 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _blob(d, x, y, c * 0.1, (198, 66, 48), rng, jitter=0.4)
    for _ in range(6):                                                               # basil
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.55 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _leaf(d, x, y, c * 0.08, (78, 130, 58), rng.uniform(0, math.pi))


def _dish_dessert(d: ImageDraw.ImageDraw, c: float, rng):
    d.ellipse([c * 0.46, c * 0.46, c * 1.54, c * 1.54], fill=(232, 196, 150))       # base
    for rr in (0.62, 0.48, 0.34, 0.2):                                              # frosting swirl
        pts = []
        for i in range(60):
            t = i / 59
            ang = t * 2 * math.pi * 1.6
            r = c * rr * (1 - t * 0.35)
            pts.append((c + r * math.cos(ang), c + r * math.sin(ang)))
        d.line(pts, fill=(244, 168, 190), width=int(c * 0.09), joint="curve")
    for _ in range(6):                                                               # berries
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.5 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _blob(d, x, y, c * 0.06, rng.choice([(196, 40, 66), (110, 52, 120), (222, 92, 60)]), rng)


def _rot_round_rect(d: ImageDraw.ImageDraw, cx: float, cy: float, w: float, h: float,
                    ang: float, fill: tuple):
    """Rounded rectangle rotated by `ang` (polygon + corner caps)."""
    cos_a, sin_a = math.cos(ang), math.sin(ang)

    def _pt(x: float, y: float) -> tuple:
        return (cx + x * cos_a - y * sin_a, cy + x * sin_a + y * cos_a)

    d.polygon([_pt(-w / 2, -h / 2 + h * 0.2), _pt(w / 2, -h / 2 + h * 0.2),
               _pt(w / 2, h / 2 - h * 0.2), _pt(-w / 2, h / 2 - h * 0.2)], fill=fill)
    for sx in (-1, 1):
        for sy in (-1, 1):
            x, y = _pt(sx * (w / 2 - h * 0.2), sy * (h / 2 - h * 0.2))
            d.ellipse([x - h * 0.2, y - h * 0.2, x + h * 0.2, y + h * 0.2], fill=fill)


def _dish_chicken(d: ImageDraw.ImageDraw, c: float, rng):
    for _ in range(7):                                                               # roasted pieces
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.42 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        w, h = c * rng.uniform(0.3, 0.42), c * rng.uniform(0.2, 0.3)
        _rot_round_rect(d, x, y, w, h, rng.uniform(0, math.pi), (172, 96, 48))
        _rot_round_rect(d, x, y, w * 0.85, h * 0.55, rng.uniform(0, math.pi), (196, 120, 62))
    for _ in range(10):                                                              # char marks
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.4 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        d.line([(x - c * 0.08, y - c * 0.03), (x + c * 0.08, y + c * 0.03)], fill=(96, 54, 34), width=int(c * 0.02))
    for _ in range(8):                                                               # garnish
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.52 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _leaf(d, x, y, c * 0.08, (88, 140, 64), rng.uniform(0, math.pi))


def _dish_soup(d: ImageDraw.ImageDraw, c: float, rng):
    d.ellipse([c * 0.36, c * 0.36, c * 1.64, c * 1.64], fill=(224, 116, 60))        # broth
    pts = []
    for i in range(50):
        t = i / 49
        ang = t * 2 * math.pi * 1.4
        r = c * 0.55 * (1 - t * 0.4)
        pts.append((c + r * math.cos(ang), c + r * math.sin(ang)))
    d.line(pts, fill=(250, 236, 210), width=int(c * 0.06), joint="curve")           # cream swirl
    for _ in range(12):                                                              # herbs + croutons
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.55 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        if rng.random() < 0.5:
            _leaf(d, x, y, c * 0.07, (74, 124, 56), rng.uniform(0, math.pi))
        else:
            d.rounded_rectangle([x - c * 0.045, y - c * 0.045, x + c * 0.045, y + c * 0.045],
                                radius=int(c * 0.015), fill=(232, 194, 128))


def _dish_sushi(d: ImageDraw.ImageDraw, c: float, rng):
    for i in range(4):
        cx = c * (0.62 + i * 0.26)
        cy = c * (0.86 + (i % 2) * 0.28)
        d.rounded_rectangle([cx - c * 0.16, cy - c * 0.12, cx + c * 0.16, cy + c * 0.12],
                            radius=int(c * 0.06), fill=(250, 246, 236))             # rice
        d.rounded_rectangle([cx - c * 0.15, cy - c * 0.13, cx + c * 0.15, cy - c * 0.02],
                            radius=int(c * 0.05), fill=(236, 128, 76))              # salmon
        d.rounded_rectangle([cx - c * 0.05, cy - c * 0.13, cx + c * 0.05, cy + c * 0.13],
                            radius=int(c * 0.02), fill=(58, 66, 54))                # nori
    for _ in range(6):                                                               # wasabi/ginger
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.5 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _blob(d, x, y, c * 0.055, rng.choice([(150, 190, 96), (240, 176, 180)]), rng)


def _dish_smoothie(d: ImageDraw.ImageDraw, c: float, rng):
    d.ellipse([c * 0.34, c * 0.34, c * 1.66, c * 1.66], fill=(176, 96, 152))        # smoothie base
    for i in range(9):                                                               # banana slices
        ang = 2 * math.pi * i / 9 + 0.3
        rad = c * 0.56
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        d.ellipse([x - c * 0.08, y - c * 0.08, x + c * 0.08, y + c * 0.08], fill=(250, 234, 176))
        d.ellipse([x - c * 0.03, y - c * 0.03, x + c * 0.03, y + c * 0.03], fill=(238, 214, 142))
    for _ in range(8):                                                               # berries
        ang = rng.uniform(0, 2 * math.pi)
        rad = c * 0.4 * math.sqrt(rng.random())
        x, y = c + rad * math.cos(ang), c + rad * math.sin(ang)
        _blob(d, x, y, c * 0.07, rng.choice([(94, 44, 116), (188, 44, 74), (58, 42, 96)]), rng)
    _leaf(d, c * 0.72, c * 0.5, c * 0.09, (86, 140, 62), 0.6)


VARIANTS = {
    "biryani": _dish_biryani,
    "pizza": _dish_pizza,
    "salad": _dish_salad,
    "burger": _dish_burger,
    "pasta": _dish_pasta,
    "dessert": _dish_dessert,
    "chicken": _dish_chicken,
    "soup": _dish_soup,
    "sushi": _dish_sushi,
    "smoothie": _dish_smoothie,
}


def render_tile(name: str, index: int, size: int = TILE) -> Image.Image:
    rng = random.Random(f"quickbite-{name}")
    bg_top, bg_bottom = BACKGROUNDS[index % len(BACKGROUNDS)]
    base = _vertical_gradient(size, bg_top, bg_bottom)
    canvas = base.resize((size * SS, size * SS), Image.Resampling.LANCZOS).convert("RGB")
    d = ImageDraw.Draw(canvas)
    c = size * SS / 2

    shadow = Image.new("RGBA", canvas.size, (0, 0, 0, 0))
    sd = ImageDraw.Draw(shadow)
    sd.ellipse([c * 0.55, c * 0.98, c * 1.48, c * 1.4], fill=(120, 70, 40, 70))
    shadow = shadow.filter(ImageFilter.GaussianBlur(int(size * SS * 0.03)))
    canvas = Image.alpha_composite(canvas.convert("RGBA"), shadow).convert("RGB")

    d = ImageDraw.Draw(canvas)
    d.ellipse([c * 0.28, c * 0.28, c * 1.72, c * 1.72], fill=PLATE_RIM)             # rim
    d.ellipse([c * 0.32, c * 0.32, c * 1.68, c * 1.68], fill=PLATE)                 # plate

    VARIANTS[name](d, c, rng)
    return canvas.resize((size, size), Image.Resampling.LANCZOS)


def render_hero(size: tuple[int, int] = (1200, 520)) -> Image.Image:
    """Dark warm banner for restaurant menu headers (bokeh-food mood)."""
    w, h = size
    img = Image.new("RGB", (w, h))
    px = img.load()
    for y in range(h):
        row = _lerp((36, 24, 20), (74, 40, 28), y / (h - 1))
        for x in range(w):
            px[x, y] = row
    rng = random.Random("quickbite-hero")
    overlay = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    od = ImageDraw.Draw(overlay)
    palette = [(238, 122, 62), (226, 178, 92), (140, 176, 92), (206, 74, 48), (250, 224, 180)]
    for _ in range(26):
        x, y = rng.uniform(0, w), rng.uniform(0, h)
        r = rng.uniform(24, 110)
        col = rng.choice(palette)
        od.ellipse([x - r, y - r, x + r, y + r], fill=(*col, rng.randint(26, 60)))
    overlay = overlay.filter(ImageFilter.GaussianBlur(38))
    return Image.alpha_composite(img.convert("RGBA"), overlay).convert("RGB")


def render_logo(size: int = 256) -> Image.Image:
    """Coral rounded-square mark with a simple white burger glyph."""
    s = size * SS
    img = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, s, s], radius=int(s * 0.24), fill=(238, 78, 52, 255))
    cx, u = s / 2, s * 0.3
    d.rounded_rectangle([cx - u, cx - u * 0.95, cx + u, cx - u * 0.45],
                        radius=int(u * 0.5), fill=(255, 252, 248, 255))             # top bun
    for i in (-0.45, 0, 0.45):                                                      # sesame
        d.ellipse([cx + i * u - u * 0.08, cx - u * 0.8, cx + i * u + u * 0.08, cx - u * 0.66],
                  fill=(238, 78, 52, 255))
    d.rounded_rectangle([cx - u * 1.04, cx - u * 0.32, cx + u * 1.04, cx - u * 0.1],
                        radius=int(u * 0.14), fill=(255, 252, 248, 255))            # patty
    d.rounded_rectangle([cx - u, cx + u * 0.06, cx + u, cx + u * 0.56],
                        radius=int(u * 0.5), fill=(255, 252, 248, 255))             # bottom bun
    return img.resize((size, size), Image.Resampling.LANCZOS)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for i, name in enumerate(VARIANTS):
        render_tile(name, i).save(OUT_DIR / f"dish_{name}.png", optimize=True)
        print(f"wrote dish_{name}.png")
    render_hero().save(OUT_DIR / "hero_banner.png", optimize=True)
    print("wrote hero_banner.png")
    render_logo().save(OUT_DIR / "logo_mark.png", optimize=True)
    print("wrote logo_mark.png")


if __name__ == "__main__":
    main()
